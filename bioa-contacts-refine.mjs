function patchContactsCss($){
  if($('#bioa-contacts-style').length)return;
  $('head').append('<style id="bioa-contacts-style">'+
    '.page-contacts .contacts-wa-btn{background:#FDFEF5!important;color:#106E45!important}'+
    '.page-contacts .contacts-wa-btn:hover{filter:none!important;background:#F3F0E4!important}'+
    '.page-contacts .contacts-wa-btn .bioa-zalo-icon{display:block!important;width:18px!important;height:18px!important;max-width:18px!important;max-height:18px!important;object-fit:contain!important;flex:0 0 18px!important}'+
    '.page-contacts .contacts-hours-time{overflow-wrap:anywhere!important}'+
    '@media(max-width:768px){.page-contacts .contacts-address-note{align-items:flex-start!important;line-height:1.5!important}}'+
  '</style>');
}

export function applyContactsRefinement($,route,lang='vi'){
  if(route!=='/contacts/')return;
  const key=lang==='en'?'en':'vi';
  const c=copy[key];
  const address=setCompanyMeta($,key,c);

  $('.contacts-page-title').text(c.title);
  $('.contacts-page-subtitle').text(c.subtitle);

  const status=$('.contacts-online-tag').first();
  if(status.length){
    const dot=status.find('.contacts-online-dot').first().toString();
    status.html(dot+'<span>'+esc(c.status)+'</span>');
  }

  const info=$('.contacts-info-block').first();
  info.attr('aria-label',c.infoAria);
  info.find('.contacts-info-title').first().text(c.infoTitle);
  info.find('.contacts-info-sub').first().text(c.infoSub);

  const infoItems=info.find('.contacts-info-grid .contacts-info-item');
  const emailCard=infoItems.eq(0);
  emailCard.attr('href','mailto:'+CONTACTS.email).attr('aria-label',c.emailAria);
  emailCard.find('.contacts-info-item-label').first().text(c.emailLabel);
  emailCard.find('.contacts-info-item-value').first().text(CONTACTS.email);

  const phoneCard=infoItems.eq(1);
  phoneCard.find('.contacts-info-item-label').first().text(c.phoneLabel);
  phoneCard.find('.contacts-info-item-value').first()
    .attr('href',CONTACTS.phoneHref)
    .attr('style','color:#fff;text-decoration:none;')
    .text(CONTACTS.phoneDisplay);
  const zalo=phoneCard.find('.contacts-wa-btn').first();
  zalo.attr('href',CONTACTS.zalo).attr('target','_blank').attr('rel','noopener noreferrer').attr('aria-label',c.zaloAria)
    .html('<img class="bioa-zalo-icon" src="/assets/zalo-bioa-owner.png" alt="" aria-hidden="true"><span>'+esc(c.zaloLabel)+'</span>');

  const addressNote=$('.contacts-address-note').first();
  addressNote.attr('href',CONTACTS.mapLink).attr('target','_blank').attr('rel','noopener noreferrer').attr('aria-label',c.addressAria);
  keepLeadingIcon(addressNote,c.addressPrefix+' '+address);

  $('.contacts-hours-label').first().text(c.companyInfo);
  const hoursGrid=$('.contacts-hours-grid').first();
  const hourTemplate=hoursGrid.find('.contacts-hours-item').first().clone();
  if(hourTemplate.length){
    hoursGrid.empty();
    const hours=hourTemplate.clone();
    hours.find('.contacts-hours-day').text(c.hoursLabel);
    hours.find('.contacts-hours-time').text(c.hoursValue);
    const tax=hourTemplate.clone();
    tax.find('.contacts-hours-day').text(c.taxLabel);
    tax.find('.contacts-hours-time').text(CONTACTS.taxId);
    hoursGrid.append(hours,tax);
  }

  const map=$('.contacts-map-block').first();
  map.attr('aria-label',c.mapAria);
  map.find('iframe').first()
    .attr('src',CONTACTS.mapEmbed)
    .attr('title',c.mapTitle)
    .attr('width','100%')
    .attr('height','100%')
    .attr('style','border:0; display:block;')
    .attr('allowfullscreen','')
    .attr('loading','lazy')
    .attr('referrerpolicy','strict-origin-when-cross-origin');

  const faq=$('.contacts-faq-block').first();
  faq.attr('aria-label',c.faqAria);
  faq.find('.contacts-faq-title').first().text(c.faqTitle);
  setFaq($,c.faq);

  patchContactsCss($);
}
