function setCopy(root,selector,value){
  const el=root.find(selector).first();
  if(!el.length)return;
  const p=el.find("p").first();
  (p.length?p:el).text(value);
}

function applyHero($,lang){
  const d=serviceContent[lang];
  $(".block-info").each((_,el)=>{
    const block=$(el);
    setCopy(block,".title",d.heroTitle);
    setCopy(block,".text",d.heroLead);
    block.find(".btn__text").text(d.heroCta);
    block.find(".composition")
      .css("background-image","url('/assets/cosmetics-hero-bioa.webp')")
      .css("background-size","cover")
      .css("background-position","center");
  });
}

function applyWhy($,lang){
  const d=serviceContent[lang];
  const block=$("#why-choose-us");
  if(!block.length)return;
  setCopy(block,".title-wrapper .title",d.whyTitle);
  const applyCards=cards=>{
    cards.each((i,el)=>{
      const row=d.why[i%d.why.length];
      const card=$(el);
      setCopy(card,".item__title",row[0]);
      setCopy(card,".item__body",row[1]);
      const img=card.find("img").first();
      if(img.length){
        img.attr("src",serviceIconMap[i%d.why.length])
          .attr("alt",row[0])
          .removeAttr("srcset sizes")
          .addClass("bioa-service-pillar-icon");
      }
    });
  };
  applyCards(block.find(".grid.desctop .item"));
  applyCards(block.find(".mobile .item"));
}

function applyProcess($,lang){
  const d=serviceContent[lang];
  $(".block-right-choice").each((_,el)=>{
    const block=$(el);
    setCopy(block,".title-wrapper .title",d.processTitle);
    block.find(".client").each((i,node)=>{
      const row=d.process[i%d.process.length];
      const client=$(node);
      setCopy(client,".client__name .h3",row[0]);
      setCopy(client,".client__description",row[1]);

      /* PATCH-F4 — source step 03 uses Merywood's mark as the Packaging & Design icon.
         Replace only this one brand-owned artwork slot; keep all other workflow icons. */
      if(i%d.process.length===2){
        const img=client.find(".client__icon img").first();
        if(img.length){
          img.attr("src","/assets/bioa-monogram-cream.svg")
            .attr("alt","Bio-A Group")
            .removeAttr("srcset sizes")
            .addClass("bioa-process-bioa-icon");
        }
      }
    });
  });
}

function applyScenarios($,lang){
  const d=serviceContent[lang];
  $(".block-reviews").each((_,el)=>{
    const block=$(el).addClass("bioa-service-scenarios");
    setCopy(block,".title-wrapper .title",d.scenariosTitle);
    block.find(".review").each((i,node)=>{
      const row=d.scenarios[i%d.scenarios.length];
      const card=$(node);
      setCopy(card,".review__text",row[0]);
      setCopy(card,".review__author-name",row[1]);
      setCopy(card,".review__author-info",row[2]);
      card.find(".review__author-quotes").remove();
    });
  });
}

function applyRange($,lang){
  const d=serviceContent[lang];
  $(".block-how-works").each((_,el)=>{
    const block=$(el);
    setCopy(block,".title-wrapper .title",d.rangeTitle);

    const slides=block.find(".swiper-wrapper").first().children(".swiper-slide");
    slides.each((i,slideNode)=>{
      const row=d.range[i];
      if(!row)return;
      const step=$(slideNode).find(".step").first();
      if(!step.length)return;

      step.find(".step__number").first().text(String(i+1).padStart(2,"0"));
      setCopy(step,".step__title",row[0]);
      setCopy(step,".step__text",row[1]);

      /* Keep Merywood's product image for each concrete product format,
         but replace the baked Merywood mark in the small icon slot only. */
      const icon=step.find(".step__icon img").first();
      if(icon.length){
        icon.attr("src","/assets/bioa-monogram-cream.svg")
          .attr("alt","Bio-A Group")
          .removeAttr("srcset sizes")
          .addClass("bioa-service-range-logo");
      }
    });
  });
}

