export function applyOtherServicesRefinement($,route,lang="vi"){
  if(route!=="/dich-vu-khac/")return;
  const key=lang==="en"?"en":"vi";
  applyHero($,key);
  applyWhy($,key);
  applyProcess($,key);
  applyScenarios($,key);
  applyRange($,key);
  localizeResidualSourceText($,key);
  patchRouteCss($);
}
